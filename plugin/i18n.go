package plugin

import "fmt"

// tr looks up key for lang (falling back to English) and formats args in.
// Languages follow ReTouch's UI language setting.
func tr(lang, key string, args ...any) string {
	m, ok := i18n[lang]
	if !ok {
		m = i18n["en"]
	}
	s, ok := m[key]
	if !ok {
		s = i18n["en"][key]
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}

